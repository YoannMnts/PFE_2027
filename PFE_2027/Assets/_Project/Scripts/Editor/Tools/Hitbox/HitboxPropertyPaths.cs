using System.Collections.Generic;
using PFE.Core.Scripts.Enemy.Attacks;

namespace PFE.Editor._Project.Scripts.Editor.Tools.Hitbox
{
    // Serialized field names of HitboxData, centralized.
    // nameof(): if a property is renamed, compilation breaks here instead of failing silently.
    internal static class HitboxPropertyPaths
    {
        public const string Hitboxes = "hitboxes";
        public const string Windows = "windows";

        public static readonly string AnimationClip = Backing(nameof(HitboxData.AnimationClip));

        // Shared by HitboxWindow.Window and AdditionalWindow.Window (same property name, same backing field)
        public static readonly string Window = Backing(nameof(HitboxWindow.Window));
        public static readonly string Flags = Backing(nameof(AdditionalWindow.Flags));
        public static readonly string Shape = Backing(nameof(HitboxWindow.Shape));
        public static readonly string Offset = Backing(nameof(HitboxWindow.Offset));
        public static readonly string Rotation = Backing(nameof(HitboxWindow.Rotation));
        public static readonly string Size = Backing(nameof(HitboxWindow.Size));

        public static readonly string Start = Backing(nameof(TimeWindow.Start));
        public static readonly string End = Backing(nameof(TimeWindow.End));

        // Fields of HitboxData (and GameDatabaseObject) already handled by the tool: everything else is
        // declared by a child type (AttackData, PushbackData...) and shown automatically in edit mode
        private static readonly HashSet<string> BaseFields = new()
        {
            "m_Script", "guidText", Hitboxes, Windows, AnimationClip,
        };

        public static bool IsBaseField(string propertyPath) => BaseFields.Contains(propertyPath);

        // Hidden field generated by the compiler for a [field: SerializeField] property
        public static string Backing(string propertyName) => $"<{propertyName}>k__BackingField";
    }
}
