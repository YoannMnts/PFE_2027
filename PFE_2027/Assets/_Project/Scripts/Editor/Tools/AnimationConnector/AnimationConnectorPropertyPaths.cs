using PFE.Core.Scripts.Enemy.Attacks;

namespace PFE.Editor._Project.Scripts.Editor.Tools.AnimationConnector
{
    // Serialized field names of AnimationData and its flags, centralized.
    // nameof(): if a property is renamed, compilation breaks here instead of failing silently.
    internal static class AnimationConnectorPropertyPaths
    {
        public const string Flags = "flags";

        // Private field of GameDatabaseObject: nameof() is not usable from the editor assembly
        public const string GuidText = "guidText";

        public static readonly string AnimationClip = Backing(nameof(AnimationData.AnimationClip));

        // Shared by every ITimedFlag (same property name, same backing field)
        public static readonly string Window = Backing(nameof(ITimedFlag.Window));
        public static readonly string Shape = Backing(nameof(Hitbox.Shape));
        public static readonly string Offset = Backing(nameof(Hitbox.Offset));
        public static readonly string Rotation = Backing(nameof(Hitbox.Rotation));
        public static readonly string Size = Backing(nameof(Hitbox.Size));

        public static readonly string Start = Backing(nameof(TimeWindow.Start));
        public static readonly string End = Backing(nameof(TimeWindow.End));

        // Hidden field generated by the compiler for a [field: SerializeField] property
        public static string Backing(string propertyName) => $"<{propertyName}>k__BackingField";
    }
}
